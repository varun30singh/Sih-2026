def get_llm_intent(
    message: str,
    memory: Optional[Dict[str, Any]] = None,
) -> Optional[Dict[str, Any]]:
    """
    Ask the LLM to understand the user's language/intent.

    The LLM does NOT answer procurement questions.
    """

    if get_llm_result is None:
        return None

    try:
        result = get_llm_result(
            message,
            memory=memory or {},
        )

        if isinstance(result, dict):
            return result

    except Exception:
        pass

    return None


def extract_llm_intent(result: Optional[Dict[str, Any]]) -> Optional[str]:
    if not result:
        return None

    possible_keys = [
        "intent",
        "procurement_intent",
        "detected_intent",
    ]

    for key in possible_keys:
        value = result.get(key)

        if isinstance(value, str) and value.strip():
            return value.strip().lower()

    return None


