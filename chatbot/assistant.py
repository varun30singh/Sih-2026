def format_delays(
    data: Dict[str, Any],
    language: str,
) -> str:

    orders = data.get("delayed_orders") or data.get("orders") or []

    if not orders:
        return localized_no_data(language)

    count = len(orders)
    total_orders = data.get("total_orders", count)
    delay_rate = data.get("delay_rate")
    rate_info = f" ({delay_rate}% of {total_orders} orders)" if delay_rate is not None else ""

    if language == "hindi":
        lines = [f"डेटा के अनुसार, {count} विलंबित ऑर्डर (delayed orders) मिले{rate_info}:"]
    elif language == "marathi":
        lines = [f"डेटा नुसार, {count} विलंबित ऑर्डर्स (delayed orders) सापडले{rate_info}:"]
    else:
        lines = [f"{count} delayed order(s) found{rate_info}:"]

    for order in orders[:10]:
        order_id = safe_text(
            order.get("procurement_id")
            or (order.get("raw") or {}).get("procurement_id")
            or order.get("order_id")
            or order.get("id", "Unknown")
        )
        supplier = safe_text(
            order.get("supplier", "Unknown supplier")
        )
        material = safe_text(
            order.get("material") or order.get("item_name", "")
        )
        delay_days = integer(
            order.get("delay_days", order.get("days_delayed", 0))
        )
        mat_str = f" ({material})" if material else ""

        if language == "hindi":
            lines.append(
                f"• {order_id}{mat_str} — {supplier} — {delay_days} दिन की देरी"
            )
        elif language == "marathi":
            lines.append(
                f"• {order_id}{mat_str} — {supplier} — {delay_days} दिवस विलंब"
            )
        else:
            lines.append(
                f"• {order_id}{mat_str} — {supplier} — {delay_days} day(s) delayed"
            )

    return "\n".join(lines)


def format_risk(
    data: Dict[str, Any],
    language: str,
) -> str:

    orders = data.get("orders") or []
    critical_orders = data.get("critical_orders") or []
    high_risk_orders = data.get("high_risk_orders") or []
    dist = data.get("risk_distribution") or {}

    critical = len(critical_orders) if critical_orders else integer(dist.get("critical", data.get("critical_count", 0)))
    high = len(high_risk_orders) if high_risk_orders else integer(dist.get("high", data.get("high_risk_count", 0)))
    total = data.get("total_at_risk") or (critical + high) or len(orders)

    if total == 0 and not orders:
        if language == "hindi":
            return "कोई high या critical risk order नहीं मिला।"
        if language == "marathi":
            return "कोणताही high किंवा critical risk order सापडला नाही."
        return "No high or critical risk orders were found."

    if language == "hindi":
        intro = (
            f"{total} order(s) currently high या critical risk में हैं: "
            f"{critical} critical और {high} high risk."
        )
    elif language == "marathi":
        intro = (
            f"{total} order(s) high किंवा critical risk मध्ये आहेत: "
            f"{critical} critical आणि {high} high risk."
        )
    else:
        intro = (
            f"{total} order(s) are currently at high or critical risk: "
            f"{critical} critical and {high} high risk."
        )

    lines = [intro]

    display_orders = critical_orders + [o for o in high_risk_orders if o not in critical_orders]
    if not display_orders:
        display_orders = orders

    for order in display_orders[:10]:
        order_id = safe_text(
            order.get("procurement_id")
            or (order.get("raw") or {}).get("procurement_id")
            or order.get("order_id")
            or order.get("id", "Unknown")
        )
        supplier = safe_text(
            order.get("supplier", "Unknown supplier")
        )
        material = safe_text(
            order.get("material") or order.get("item_name", "")
        )
        score = integer(
            order.get("risk_score", order.get("score", 0))
        )
        level = safe_text(
            order.get("risk_level", "risk")
        ).lower()
        reasons = order.get("reasons", [])
        reasons_str = f" [Why: {', '.join(reasons)}]" if reasons else ""
        mat_str = f" ({material})" if material else ""

        lines.append(
            f"• {order_id}{mat_str} — {supplier} — {level} risk ({score}/100){reasons_str}"
        )

    return "\n".join(lines)


