def correct_common_typos(text: str) -> str:
    """Normalizes common procurement typos before intent detection."""
    if not text:
        return ""
    words = text.split()
    corrected = []
    for w in words:
        clean_w = re.sub(r"[^\w\u0900-\u097F]", "", w).lower()
        if clean_w in COMMON_TYPO_MAP:
            replacement = COMMON_TYPO_MAP[clean_w]
            trailing = re.findall(r"[^\w\u0900-\u097F]+$", w)
            suffix = trailing[0] if trailing else ""
            corrected.append(replacement + suffix)
        else:
            corrected.append(w)
    return " ".join(corrected)


