def format_procurement_response(
    intent: str,
    result: Dict[str, Any],
    language: str,
    user_message: str = "",
) -> str:

    data = unwrap_result(result)

    if not data:
        return localized_no_data(language)

    if intent in ["supplier_comparison", "compare"]:
        return format_compare(data, language)

    if intent == "supplier_delays":
        return format_supplier_delays(data, language)

    if intent == "delays":
        return format_delays(data, language)

    if intent == "risk":
        return format_risk(data, language)

    if intent == "critical":
        return format_critical(data, language)

    if intent == "expensive":
        return format_expensive(data, language)

    if intent == "supplier_performance":
        return format_supplier_performance(data, language, user_message=user_message)

    if intent == "health":
        return format_health(data, language)

    if intent == "recommendations":
        return format_recommendations(data, language)

    if intent == "total_cost":
        return format_total_cost(data, language)

    if intent == "average_cost":
        return format_average_cost(data, language)

    if intent == "supplier_cost":
        return format_supplier_cost(data, language)

    if intent == "upcoming_deliveries":
        return format_upcoming_deliveries(data, language)

    if intent == "materials":
        return format_materials(data, language)

    if intent == "supplier_summary":
        return format_supplier_summary(data, language)

    if intent == "orders":
        return format_orders(data, language)

    if intent == "dashboard":
        return format_dashboard(data, language)

    return format_generic(data, language)


