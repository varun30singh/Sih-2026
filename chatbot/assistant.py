    # --------------------------------------------------------
    # PUBLIC ASK
    # --------------------------------------------------------

    def ask(self, message: str, language: Optional[str] = None) -> str:

        raw_message = normalize_text(message)
        message = correct_common_typos(raw_message)

        if not message:
            return localized_basic_response(
                "unknown",
                language or self.last_language or "english",
            )

        lower_msg = message.lower()

        # ----------------------------------------------------
        # Explicit Language Detection inside user query
        # ----------------------------------------------------
        explicit_lang = None
        if (
            re.search(r"\b(hindi\s*me(in)?|in\s*hindi|hindi\s*mein\s*(explain|batao|bataiye)|explain\s*in\s*hindi)\b", lower_msg)
            or "हिंदी में" in message
            or "हिंदी मे" in message
        ):
            explicit_lang = "hindi"
        elif (
            re.search(r"\b(marathi\s*(madhe|t)?|in\s*marathi|marathi\s*madhe\s*(explain|sanga)|explain\s*in\s*marathi)\b", lower_msg)
            or "मराठीत" in message
            or "मराठी मध्ये" in message
        ):
            explicit_lang = "marathi"
        elif re.search(r"\b(in\s*english|english\s*me(in)?|english\s*madhe|explain\s*in\s*english)\b", lower_msg):
            explicit_lang = "english"

        # Normalize target response language if provided by UI / session
        forced_language = None
        if language and isinstance(language, str):
            clean_lang = language.strip().lower()
            if clean_lang in ["english", "hindi", "marathi", "hinglish", "marathi_english"]:
                forced_language = clean_lang

        if explicit_lang:
            language = explicit_lang
        elif forced_language:
            language = forced_language
        else:
            language = detect_language(message)

            # Follow-up language inheritance
            if is_follow_up(message) and self.last_language:
                if DEVANAGARI_RE.search(message):
                    if self.last_language in ["hindi", "marathi"]:
                        language = self.last_language
                    elif language in ["hindi", "marathi"]:
                        pass
                    else:
                        language = "hindi"
                else:
                    if self.last_language in ["english", "hinglish", "marathi_english"]:
                        language = self.last_language
                    elif language in ["english", "hinglish", "marathi_english"]:
                        pass
                    else:
                        language = "english"
            elif language == "unknown":
                language = self.last_language or "english"

        # ----------------------------------------------------
        # Ultra-short Ambiguous Queries (e.g. "score?", "score")
        # ----------------------------------------------------
        clean_word = re.sub(r"[^\w\u0900-\u097F]", "", message).strip().lower()
        if clean_word in ["score", "scroe", "स्कोर", "स्कोअर"]:
            clarification = AMBIGUOUS_SHORT_CLARIFICATIONS.get("score", {}).get(
                language,
                AMBIGUOUS_SHORT_CLARIFICATIONS["score"]["english"]
            )
            self.update_memory(message, "ambiguous_score", language)
            self.add_history(message, clarification, "ambiguous_score", language)
            return clarification

        # ----------------------------------------------------
        # Direct Short Metric Queries
        # ----------------------------------------------------
        if clean_word in ["delays", "delay", "देरी"]:
            return self.ask_procurement("Which orders are delayed?", "delays", language, user_message=message)
        if clean_word in ["risk", "risks", "जोखिम", "जोखीम"]:
            return self.ask_procurement("Which orders are at risk?", "risk", language, user_message=message)
        if clean_word in ["cost", "spend", "spending", "खर्च"]:
            return self.ask_procurement("What is the total procurement cost?", "total_cost", language, user_message=message)
        if clean_word in ["suppliers", "सप्लायर्स", "पुरवठादार"]:
            return self.ask_procurement("Show supplier summary.", "supplier_summary", language, user_message=message)
        if clean_word in ["orders", "ऑर्डर्स"]:
            return self.ask_procurement("Show all orders.", "orders", language, user_message=message)
        if clean_word in ["critical"]:
            return self.ask_procurement("Show critical orders.", "critical", language, user_message=message)

        # ----------------------------------------------------
        # Conceptual / Formula Understanding
        # ----------------------------------------------------
        concept_res = detect_concept_intent(message)
        if concept_res:
            concept_key, is_calc = concept_res
            if concept_key == "score_calc":
                clarification = AMBIGUOUS_SHORT_CLARIFICATIONS.get("score_calc", {}).get(
                    language,
                    AMBIGUOUS_SHORT_CLARIFICATIONS["score_calc"]["english"]
                )
                self.update_memory(message, "ambiguous_score_calc", language)
                self.add_history(message, clarification, "ambiguous_score_calc", language)
                return clarification

            if is_calc:
                response = get_calculation_explanation(concept_key, language)
                intent_label = f"concept_calc_{concept_key}"
            else:
                response = get_concept_explanation(concept_key, language)
                intent_label = f"concept_def_{concept_key}"

            if response:
                self.update_memory(message, intent_label, language)
                self.add_history(message, response, intent_label, language)
                return response

        # ----------------------------------------------------
        # Analytical Reasoning (Why questions)
        # ----------------------------------------------------
        analytical_resp = self.handle_analytical_query(message, language)
        if analytical_resp:
            self.update_memory(message, "analytical_query", language)
            self.add_history(message, analytical_resp, "analytical_query", language)
            return analytical_resp

        # ----------------------------------------------------
        # Best Supplier Recommendations
        # ----------------------------------------------------
        best_sup_resp = self.handle_best_supplier_recommendation(message, language)
        if best_sup_resp:
            self.update_memory(message, "best_supplier_recommendation", language)
            self.add_history(message, best_sup_resp, "best_supplier_recommendation", language)
            return best_sup_resp

        # ----------------------------------------------------
        # Contextual Conceptual-to-Data Follow-ups
        # ----------------------------------------------------
        if any(p in lower_msg for p in ["is our score good", "is health score good", "score accha hai", "score achha hai", "score changla aahe"]):
            health_data = self.procurement.engine.procurement_health() if self.procurement else {}
            score = health_data.get("health_score", 46)
            if language == "hindi":
                resp = f"नहीं, हमारा वर्तमान प्रोक्योरमेंट हेल्थ स्कोर {score}/100 है, जो 'उच्च जोखिम' (High Risk) श्रेणी में आता है (60 से कम)। इसमें 4 विलंबित ऑर्डर और 3 गंभीर (Critical) ऑर्डर हैं जिन पर तत्काल ध्यान देने की आवश्यकता है।"
            elif language == "hinglish":
                resp = f"Nahi, humara current Procurement Health Score {score}/100 hai, jo High Risk category mein aata hai (60 se kam). Isme 4 delayed orders aur 3 critical shipments hain."
            elif language == "marathi":
                resp = f"नाही, आमचा सध्याचा प्रोक्योरमेंट हेल्थ स्कोअर {score}/100 आहे, जो 'उच्च जोखीम' (High Risk) श्रेणीत मोडतो. यात 4 विलंबित ऑर्डर्स आणि 3 गंभीर ऑर्डर्स आहेत ज्यांवर त्वरित लक्ष देणे आवश्यक आहे."
            elif language == "marathi_english":
                resp = f"Nahi, aamcha Health Score sadhya {score}/100 aahe, jo High Risk category madhe yeto (below 60)."
            else:
                resp = f"No, our current Procurement Health Score is {score}/100, which falls into the 'High Risk' tier (below the 60-point safety threshold). There are currently 4 delayed orders and 3 critical-priority shipments requiring attention."
            self.update_memory(message, "health", language, data=health_data)
            self.add_history(message, resp, "health", language)
            return resp

        if any(p in lower_msg for p in ["causing the problem", "dikkat de raha hai", "problem aahe", "kon dikkat"]):
            return self.ask_procurement("Which supplier has the most delays?", "supplier_delays", language, user_message=message)

        # ----------------------------------------------------
        # Intent
        # ----------------------------------------------------

        intent, llm_result = self.determine_intent(message)

        # ----------------------------------------------------
        # Comparison Follow-up
        # ----------------------------------------------------
        if (
            intent in ["unknown", "delays", "supplier_delays", "supplier_comparison", "risk", "supplier_performance"]
            and is_comparison_followup(message, self.last_intent)
            and self.last_comparison_data
            and len(extract_comparison_suppliers(message)) < 2
        ):
            response = format_comparison_followup(
                message,
                self.last_comparison_data,
                language,
            )
            self.update_memory(
                message,
                "supplier_comparison",
                language,
                data=self.last_comparison_data,
                comparison_data=self.last_comparison_data,
            )
            self.add_history(
                message,
                response,
                "supplier_comparison",
                language,
            )
            return response

        # ----------------------------------------------------
        # Multi-turn Comparison State: Waiting for 2nd supplier
        # ----------------------------------------------------
        if self.last_intent == "compare_need_second" and self.last_single_supplier:
            dyn_suppliers = [s["supplier"] for s in self.procurement.engine.supplier_summary()] if self.procurement else KNOWN_SUPPLIERS
            cands = extract_comparison_suppliers(message, dyn_suppliers)
            second_name = cands[0] if cands else message.strip(" .?!,")
            if second_name:
                cmp_res = self.procurement.engine.compare_suppliers(self.last_single_supplier, second_name) if self.procurement else {"success": False}
                if cmp_res.get("success"):
                    response = format_compare(cmp_res, language)
                    self.update_memory(
                        message,
                        "supplier_comparison",
                        language,
                        data=cmp_res,
                        comparison_data=cmp_res,
                    )
                    self.add_history(
                        message,
                        response,
                        "supplier_comparison",
                        language,
                    )
                    return response
                else:
                    payload = {"success": False, "unknown_supplier": second_name, "available_suppliers": dyn_suppliers}
                    response = format_compare(payload, language)
                    self.update_memory(
                        message,
                        "compare_need_second",
                        language,
                        data=payload,
                        single_supplier=self.last_single_supplier,
                    )
                    self.add_history(
                        message,
                        response,
                        "compare_need_second",
                        language,
                    )
                    return response

        # ----------------------------------------------------
        # Multi-turn Comparison State: Waiting for both suppliers
        # ----------------------------------------------------
