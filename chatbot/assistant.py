    # --------------------------------------------------------
    # INTENT
    # --------------------------------------------------------

    def determine_intent(
        self,
        message: str,
    ) -> Tuple[str, Optional[Dict[str, Any]]]:

        local_intent = detect_local_intent(message)

        # Deterministic detection wins for known procurement queries.
        if local_intent != "unknown":
            return local_intent, None

        llm_result = get_llm_intent(
            message,
            memory={
                "last_intent": self.last_intent,
                "last_language": self.last_language,
                "last_procurement_question": self.last_procurement_question,
            },
        )

        llm_intent = normalize_intent(
            extract_llm_intent(llm_result)
        )

        if llm_intent != "unknown":
            return llm_intent, llm_result

        return "unknown", llm_result

