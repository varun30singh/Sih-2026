def extract_comparison_suppliers(
    text: str,
    dynamic_suppliers: Optional[List[str]] = None,
) -> List[str]:
    clean_text = text.strip()
    lower = clean_text.lower()

    known = dynamic_suppliers or KNOWN_SUPPLIERS
    alias_map = dict(SUPPLIER_ALIASES)
    for s in known:
        alias_map[s.lower()] = s
        first_word = s.split()[0].lower()
        if len(first_word) >= 3 and first_word not in alias_map:
            alias_map[first_word] = s

    found_known = []
    sorted_aliases = sorted(alias_map.keys(), key=len, reverse=True)
    matched_spans = []

    for alias in sorted_aliases:
        pattern = r"\b" + re.escape(alias) + r"\b"
        for m in re.finditer(pattern, lower):
            span = m.span()
            if not any(s[0] <= span[0] and span[1] <= s[1] for s in matched_spans):
                matched_spans.append(span)
                canonical = alias_map[alias]
                found_known.append((span[0], canonical))

    found_known.sort(key=lambda x: x[0])
    ordered_known = []
    for pos, name in found_known:
        if name not in ordered_known:
            ordered_known.append(name)

    if len(ordered_known) >= 2:
        return ordered_known[:2]

    has_explicit_comparison_kw = any(
        (re.search(r"\b" + re.escape(kw) + r"\b", lower) if kw in ["vs", "vs.", "v/s"] else kw in lower)
        for kw in COMPARISON_KEYWORDS
    )

    if len(ordered_known) >= 1 or has_explicit_comparison_kw:
        split_patterns = [
            r"\bvs\.?\b",
            r"\bversus\b",
            r"\bv/s\b",
            r"\band\b",
            r"\baur\b",
            r"\bani\b",
            r"\bya\b",
            r"(?:^|\s+)किंवा(?:\s+|$)",
            r"(?:^|\s+)और(?:\s+|$)",
            r"(?:^|\s+)या(?:\s+|$)",
        ]
        trimmed = re.sub(
            r"^(please\s+)?(compare(\s+the\s+performance\s+of)?|tell me the difference between|difference between)\s+",
            "",
            clean_text,
            flags=re.IGNORECASE,
        )
        trimmed = re.sub(
            r"\s+(ko\s+compare\s+karo|compare\s+kara|ki\s+tulna\s+karo|ची\s+तुलना\s+करा|की\s+तुलना\s+करो).*$",
            "",
            trimmed,
            flags=re.IGNORECASE,
        )

        for sp in split_patterns:
            parts = re.split(sp, trimmed, flags=re.IGNORECASE)
            if len(parts) >= 2:
                cand1 = parts[0].strip(" ?,.:;!-")
                cand2 = parts[1].strip(" ?,.:;!-")
                words1 = [w for w in cand1.split() if w.lower() not in COMPARISON_STOPWORDS]
                words2 = [w for w in cand2.split() if w.lower() not in COMPARISON_STOPWORDS]
                c1 = " ".join(words1).strip(" ?,.:;!-")
                c2 = " ".join(words2).strip(" ?,.:;!-")
                final1 = alias_map.get(c1.lower(), c1) if c1 else ""
                final2 = alias_map.get(c2.lower(), c2) if c2 else ""
                candidates = [c for c in [final1, final2] if c]
                if len(candidates) >= 2:
                    return candidates[:2]
                elif len(candidates) == 1 and not ordered_known:
                    return candidates

    return ordered_known


def is_comparison_query(
    text: str,
    dynamic_suppliers: Optional[List[str]] = None,
) -> bool:
    clean = text.strip()
    lower = clean.lower()

    for kw in COMPARISON_KEYWORDS:
        if kw in ["vs", "vs.", "v/s"]:
            if re.search(r"\b" + re.escape(kw) + r"\b", lower):
                return True
        elif kw in lower:
            return True

    suppliers = extract_comparison_suppliers(text, dynamic_suppliers)
    if len(suppliers) >= 2:
        return True

    return False


