def format_generic(
    data: Dict[str, Any],
    language: str,
) -> str:

    # Try common useful fields.
    if "message" in data:
        return safe_text(data["message"])

    if "text" in data:
        return safe_text(data["text"])

    if "result" in data and isinstance(data["result"], str):
        return data["result"]

    # Fall back to compact structured output.
    lines = []

    for key, value in data.items():

        if isinstance(value, (dict, list)):
            continue

        label = key.replace("_", " ").title()

        lines.append(
            f"• {label}: {value}"
        )

    if lines:
        return "\n".join(lines)

    return localized_no_data(language)


