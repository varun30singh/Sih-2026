def is_count_follow_up(text: str) -> bool:
    cleaned = re.sub(r"[^\w\s\u0900-\u097F]", "", text).strip().lower()
    count_words = {
        "kitne", "kitna", "kiti", "how many", "how much",
        "kitne orders", "kiti orders", "how many orders", "kitne delay",
        "kiti delay", "kitna delay", "kitne delayed", "how many delayed",
        "कितने", "कितना", "किती", "कितने orders", "किती orders",
    }
    if cleaned in count_words:
        return True
    return any(re.search(p, cleaned) for p in COUNT_FOLLOW_UP_PATTERNS)


def is_follow_up(text: str) -> bool:
    if is_count_follow_up(text):
        return True

    cleaned = re.sub(r"[^\w\s\u0900-\u097F]", "", text).strip().lower()
    lower = normalize_text(text).lower()

    if len(lower.split()) <= 4:
        short_followups = {
            "why",
            "how",
            "details",
            "more",
            "show more",
            "aur batao",
            "aur bata",
            "ajun sang",
            "ajun dakhva",
            "more details",
            "which ones",
            "which orders",
            "kaunse",
            "kontya",
        }

        if cleaned in short_followups or lower in short_followups:
            return True

    return any(re.search(pattern, lower) for pattern in FOLLOW_UP_PATTERNS)


