def format_risk(
    data: Dict[str, Any],
    language: str,
) -> str:

    orders = data.get("orders") or []
    critical_orders = data.get("critical_orders") or []
    high_risk_orders = data.get("high_risk_orders") or []
    dist = data.get("risk_distribution") or {}

    critical = len(critical_orders) if critical_orders else integer(dist.get("critical", data.get("critical_count", 0)))
    high = len(high_risk_orders) if high_risk_orders else integer(dist.get("high", data.get("high_risk_count", 0)))
    total = data.get("total_at_risk") or (critical + high) or len(orders)

    if total == 0 and not orders:
        if language == "hindi":
            return "कोई high या critical risk order नहीं मिला।"
        if language == "hinglish":
            return "Koi high ya critical risk order nahi mila."
