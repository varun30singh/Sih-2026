def format_comparison_followup(
    question: str,
    data: Dict[str, Any],
    language: str,
) -> str:
    a = data.get("supplier_a", {})
    b = data.get("supplier_b", {})
    cmp = data.get("comparison", {})

    name_a = safe_text(a.get("supplier", "Supplier A"))
    name_b = safe_text(b.get("supplier", "Supplier B"))

    del_a = integer(a.get("delayed"))
    del_b = integer(b.get("delayed"))

    cost_a = float(a.get("total_cost") or 0)
    cost_b = float(b.get("total_cost") or 0)

    score_a = integer(a.get("performance_score", 20))
    score_b = integer(b.get("performance_score", 20))

    rate_a = f"{float(a.get('delay_rate', 0)):.1f}%"
    rate_b = f"{float(b.get('delay_rate', 0)):.1f}%"

    q_lower = question.lower()

    # More delays query
    if any(x in q_lower for x in ["more delay", "more delays", "higher delay", "highest delay", "zyada delay", "jyada delay", "jast delay", "जास्त"]):
        if del_a > del_b:
            high_name, high_del, low_name, low_del = name_a, del_a, name_b, del_b
        elif del_b > del_a:
            high_name, high_del, low_name, low_del = name_b, del_b, name_a, del_a
        else:
            if language == "hindi":
                return f"दोनों सप्लायर्स ({name_a} और {name_b}) के delayed orders बराबर हैं ({del_a})।"
            if language == "marathi":
                return f"दोन्ही suppliers ({name_a} आणि {name_b}) चे delays समान आहेत ({del_a} delayed orders)."
            return f"Both {name_a} and {name_b} have the same number of delays ({del_a} delayed orders)."

        if language == "hindi":
            return f"{high_name} में ज्यादा delays हैं — {high_del} delayed order(s), जबकि {low_name} के {low_del} delayed order(s) हैं।"
        if language == "marathi":
            return f"{high_name} ला जास्त delays आहेत — {high_del} delayed order(s), तर {low_name} चे {low_del} delayed order(s) आहेत।"
        return f"{high_name} has more delays with {high_del} delayed order(s) compared to {low_name}'s {low_del} delayed order(s)."

    # Fewer delays query
    if any(x in q_lower for x in ["fewer delay", "fewer delays", "less delay", "kam delay", "kami delay", "कमी"]):
        if del_a < del_b:
            low_name, low_del, high_name, high_del = name_a, del_a, name_b, del_b
        elif del_b < del_a:
            low_name, low_del, high_name, high_del = name_b, del_b, name_a, del_a
        else:
            if language == "hindi":
                return f"दोनों सप्लायर्स ({name_a} और {name_b}) के delayed orders बराबर हैं ({del_a})।"
            return f"Both {name_a} and {name_b} have the same number of delays ({del_a} delayed orders)."

        if language == "hindi":
            return f"{low_name} में कम delays हैं — {low_del} delayed order(s), जबकि {high_name} के {high_del} delayed order(s) हैं।"
        if language == "marathi":
            return f"{low_name} ला कमी delays आहेत — {low_del} delayed order(s), तर {high_name} चे {high_del} delayed order(s) आहेत।"
        return f"{low_name} has fewer delays with {low_del} delayed order(s) compared to {high_name}'s {high_del} delayed order(s)."

    # Better / overall query
    if any(x in q_lower for x in ["better", "best", "accha", "achha", "changla", "behtar", "बेहतर", "चांगला"]):
        better = cmp.get("better_overall") or (name_a if del_a < del_b else name_b)
        score = score_a if better == name_a else score_b
        d_cnt = del_a if better == name_a else del_b
        other_cnt = del_b if better == name_a else del_a
        if language == "hindi":
            return f"{better} कुल मिलाकर बेहतर है, इसके delays कम हैं ({d_cnt} बनाम {other_cnt}) और परफॉर्मेंस स्कोर {score}/100 है।"
        if language == "marathi":
            return f"{better} एकंदरीत उत्तम आहे, याचे delays कमी आहेत ({d_cnt} विरुद्ध {other_cnt}) आणि परफॉर्मन्स स्कोअर {score}/100 आहे."
        return f"{better} is performing better overall, with fewer delays ({d_cnt} vs {other_cnt}) and a performance score of {score}/100."

    # Cost / price query
    if any(x in q_lower for x in ["cost", "spend", "expensive", "cheaper", "mehenga", "sasta", "kharcha", "किंमत"]):
        if any(x in q_lower for x in ["cheap", "lower", "less", "kam", "kami", "sasta"]):
            win_name = name_a if cost_a < cost_b else name_b
            win_c = money(min(cost_a, cost_b))
            lose_c = money(max(cost_a, cost_b))
            if language == "hindi":
                return f"{win_name} का कुल खर्च कम है ({win_c} बनाम {lose_c})।"
            return f"{win_name} has lower spend at {win_c} compared to {lose_c}."
        else:
            high_name = name_a if cost_a > cost_b else name_b
            high_c = money(max(cost_a, cost_b))
            low_c = money(min(cost_a, cost_b))
            if language == "hindi":
                return f"{high_name} का कुल खर्च ज्यादा है ({high_c} बनाम {low_c})।"
            return f"{high_name} has higher spend at {high_c} compared to {low_c}."

    # Why query
    if any(x in q_lower for x in ["why", "kyun", "kyu", "का", "क्यों"]):
        better = cmp.get("better_overall") or (name_a if del_a <= del_b else name_b)
        other = name_b if better == name_a else name_a
        d_cnt = del_a if better == name_a else del_b
        other_cnt = del_b if better == name_a else del_a
        score = score_a if better == name_a else score_b
        other_score = score_b if better == name_a else score_a
        rate_better = rate_a if better == name_a else rate_b
        rate_other = rate_b if better == name_a else rate_a

        if language == "hindi":
            return (
                f"{better} इसलिए बेहतर है क्योंकि इसमें विलंबित ऑर्डर कम हैं ({d_cnt} बनाम {other_cnt}), "
                f"देरी की दर कम है ({rate_better} बनाम {rate_other}), और इसका परफॉरमेंस स्कोर {score}/100 है "
                f"(जबकि {other} का स्कोर {other_score}/100 है)। इससे इसकी डिलीवरी विश्वसनीयता अधिक है।"
            )
        if language == "marathi":
            return (
                f"{better} या कारणास्तव चांगला पर्याय आहे कारण यात विलंबित ऑर्डर्स कमी आहेत ({d_cnt} विरुद्ध {other_cnt}), "
                f"विलंब दर कमी आहे ({rate_better} विरुद्ध {rate_other}) आणि स्कोअर {score}/100 आहे "
                f"(तर {other} चा स्कोअर {other_score}/100 आहे)."
            )
        return (
            f"{better} is rated better because it has fewer delayed orders ({d_cnt} vs {other_cnt}), "
            f"a lower delay rate ({rate_better} vs {rate_other}), and a higher performance score of {score}/100 "
            f"(compared to {other}'s {other_score}/100), ensuring higher delivery reliability."
        )

    # Delays query
    if any(x in q_lower for x in ["what about delay", "what about delays", "delays", "delay", "देरी", "विलंब"]):
        if language == "hindi":
            return (
                f"देरी (Delays) की तुलना:\n"
                f"• {name_a}: {del_a} विलंबित ऑर्डर ({rate_a} देरी दर)\n"
                f"• {name_b}: {del_b} विलंबित ऑर्डर ({rate_b} देरी दर)"
            )
        if language == "marathi":
            return (
                f"विलंबाची (Delays) तुलना:\n"
                f"• {name_a}: {del_a} विलंबित ऑर्डर्स ({rate_a} विलंब दर)\n"
                f"• {name_b}: {del_b} विलंबित ऑर्डर्स ({rate_b} विलंब दर)"
            )
        return (
            f"Delivery Delays Comparison:\n"
            f"• {name_a}: {del_a} delayed order(s) ({rate_a} delay rate)\n"
            f"• {name_b}: {del_b} delayed order(s) ({rate_b} delay rate)"
        )

    # Risk query
    if any(x in q_lower for x in ["riskier", "risky", "risk", "जोखिम", "जोखीम"]):
        if del_a > del_b or score_a < score_b:
            risk_name, safe_name = name_a, name_b
            risk_del, safe_del = del_a, del_b
            risk_sc, safe_sc = score_a, score_b
        elif del_b > del_a or score_b < score_a:
            risk_name, safe_name = name_b, name_a
            risk_del, safe_del = del_b, del_a
            risk_sc, safe_sc = score_b, score_a
        else:
            risk_name, safe_name = None, None

        if risk_name:
            if language == "hindi":
                return f"{risk_name} में अधिक जोखिम है क्योंकि इसके विलंबित ऑर्डर ज्यादा हैं ({risk_del} बनाम {safe_del}) और परफॉरमेंस स्कोर केवल {risk_sc}/100 है (बनाम {safe_name} का {safe_sc}/100)।"
            if language == "marathi":
                return f"{risk_name} मध्ये जास्त जोखीम आहे कारण यात विलंबाचे प्रमाण जास्त आहे ({risk_del} विरुद्ध {safe_del}) आणि स्कोअर फक्त {risk_sc}/100 आहे."
            return f"{risk_name} carries higher risk due to more delivery delays ({risk_del} vs {safe_del}) and a lower score of {risk_sc}/100 compared to {safe_name} ({safe_sc}/100)."
        else:
            if language == "hindi":
                return f"दोनों सप्लायर्स ({name_a} और {name_b}) का जोखिम स्तर समान है।"
            return f"Both {name_a} and {name_b} present comparable operational risk levels."

    better = cmp.get("better_overall", name_a)
    if language == "hindi":
        return f"तुलना के अनुसार {better} बेहतर स्थिति में है (कम delays और कम खर्च)।"
    return f"Based on the comparison, {better} is performing better overall with fewer delays and lower financial exposure."


