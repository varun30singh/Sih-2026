            f"• फसल: {crop} — {q_qtl:.1f} क्विंटल ({q_kg:,.0f} किग्रा)\n"
            f"• स्लॉट समय: {slot}\n"
            f"• कतार की स्थिति: {ahead} किसान आगे हैं (वर्तमान सेवा: टोकन {cur_turn})\n"
            f"• अनुमानित प्रतीक्षा समय: {wait_min} मिनट\n"
