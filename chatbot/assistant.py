def normalize_text(text: str) -> str:
    """Normalize user input while preserving Devanagari."""
    text = str(text or "").strip()
    text = re.sub(r"\s+", " ", text)
    return text


def detect_language(text: str) -> str:
    """
    Detect language & script:
        english
        hindi (Devanagari script)
        marathi (Devanagari script)
        unknown
    """

    text = normalize_text(text)

    if not text:
        return "unknown"

    lower = text.lower()

    # --------------------------------------------------------
    # 1. Explicit Language Instructions in User Message
    # --------------------------------------------------------
    if (
        re.search(r"\b(hindi\s*me(in)?|in\s*hindi|hindi\s*mein\s*(explain|batao|bataiye)|explain\s*in\s*hindi)\b", lower)
        or "हिंदी में" in text
        or "हिंदी मे" in text
    ):
        return "hindi"

    if (
        re.search(r"\b(marathi\s*(madhe|t)?|in\s*marathi|marathi\s*madhe\s*(explain|sanga)|explain\s*in\s*marathi)\b", lower)
        or "मराठीत" in text
        or "मराठी मध्ये" in text
    ):
        return "marathi"

    if re.search(r"\b(in\s*english|english\s*me(in)?|english\s*madhe|explain\s*in\s*english)\b", lower):
        return "english"

    # --------------------------------------------------------
    # 2. Devanagari Script Detection
    # --------------------------------------------------------

    if DEVANAGARI_RE.search(text):
        devanagari_words = set(re.findall(r"[\u0900-\u097F]+", text))

        marathi_markers = {
            "आहे", "आहेत", "काय", "कोण", "कोणत्या", "किती", "सगळ्यात",
            "जास्त", "कमी", "मला", "दाखवा", "सांगा", "उद्या", "आज", "मध्ये",
            "ला", "ना", "द्या", "करा", "पाहिजे", "नवीन", "सर्व", "त्यांचे", "यांचे",
            "म्हणजे", "समजावून", "तुलना", "स्कोअर", "खरेदी", "पुरवठादार",
            "आमचा", "आमची", "आमचे", "का", "कशासाठी", "कशाने", "विलंब", "कामगिरी",
            "पुरवठादाराचा", "पुरवठादाराचे", "पुरवठादारांना", "सर्वाधिक", "महागडे",
            "माझं", "माझा", "माझी", "माझे", "कधी", "येणार", "येईल", "मिळणार", "मिळाले",
            "विकले", "विक्री", "गहू", "शेतकरी", "रांग", "हमीभाव", "स्थिती", "पाहिजेत", "सापडला"
        }

        hindi_markers = {
            "है", "हैं", "क्या", "कौन", "किस", "कितना", "कितने", "सबसे",
            "ज्यादा", "कम", "मुझे", "बताओ", "दिखाओ", "आज", "कल", "में",
            "को", "का", "की", "के", "और", "चाहिए", "नया", "सभी", "उनके", "इनके",
            "होता", "होती", "करो", "कीजिए", "तुलना", "स्कोर", "खरीद",
            "हमारा", "हमारी", "हमारे", "देरी", "प्रदर्शन", "सप्लायर", "कदम", "उठाएं",
            "कब", "आएगा", "मिलेगा", "बेचा", "गेहूं", "किसान", "कतार"
        }

        marathi_score = len(devanagari_words & marathi_markers)
        hindi_score = len(devanagari_words & hindi_markers)

        # Distinctive Marathi words that decisively imply Marathi
        strong_marathi = {"आहे", "आहेत", "काय", "आमचा", "आमची", "आमचे", "स्कोअर", "खरेदी", "कामगिरी", "पुरवठादार", "महागडे", "दाखवा", "सांगा", "माझं", "कधी", "येणार", "येईल", "गहू", "रांग", "हमीभाव"}
        if devanagari_words & strong_marathi:
            marathi_score += 2

        if marathi_score > hindi_score:
            return "marathi"
        if hindi_score > marathi_score:
            return "hindi"

        # Default Devanagari with technical/loan words to Hindi
        return "hindi"

    # --------------------------------------------------------
    # 3. Roman Script: Check Word Markers
    # --------------------------------------------------------

    words = re.findall(r"[a-zA-Z]+", lower)

    hindi_score = sum(1 for word in words if word in HINDI_WORDS)
    marathi_score = sum(1 for word in words if word in MARATHI_WORDS)

    # Marathi-specific combinations
    marathi_phrases = [
        "saglyat jast",
        "kontya supplier",
        "kontya order",
        "kiti aahe",
        "kiti ahet",
        "delay aahe",
        "risk madhe",
        "risk madhye",
        "dakhva",
        "sanga",
        "pahije",
        "kasa aahe",
        "kashi aahe",
        "kase aahe",
        "mhanje kay",
    ]

    # Hindi-specific combinations
    hindi_phrases = [
        "sabse zyada",
        "sabse jyada",
        "kis supplier",
        "kaunse supplier",
        "kaunse order",
        "kitna hai",
        "kitne hain",
        "delay hai",
        "risk mein",
        "dikhao",
        "batao",
        "kiska delay",
        "kya hai",
        "kya hota",
        "kaisa hai",
        "kaisi hai",
        "samjhao",
    ]

    marathi_phrase_score = sum(
        1 for phrase in marathi_phrases if phrase in lower
    )

    hindi_phrase_score = sum(
        1 for phrase in hindi_phrases if phrase in lower
    )

    marathi_score += marathi_phrase_score * 2
    hindi_score += hindi_phrase_score * 2

    # If NO Hindi or Marathi marker words are present, it is pure English
    if hindi_score == 0 and marathi_score == 0:
        return "english"

    if marathi_score > hindi_score:
        return "marathi"

    if hindi_score > marathi_score:
        return "hindi"

    # Equal non-zero scores: check distinctive Marathi markers
    if any(x in lower for x in ["aahe", "ahet", "kontya", "saglyat", "dakhva", "sanga", "kiti", "la", "madhye", "madhe", "kasa"]):
        return "marathi"

    return "hindi"


